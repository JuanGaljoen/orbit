// Pre-assembles the vendored Floorplan viewer (src/vendor/floorplan/assets) into one string, mirroring
// `page()` in Floorplan's scripts/build.mjs, leaving only the data and title placeholders. Run via
// `pnpm floorplan:template`; the output is committed so the app needs no fs access at runtime.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../src/vendor/floorplan");
const assets = path.join(root, "assets");
const read = (...p) => fs.readFileSync(path.join(assets, ...p), "utf8");
const b64 = (...p) => fs.readFileSync(path.join(assets, ...p)).toString("base64");
const noClose = (s) => s.replace(/<\/script/gi, "<\\/script");

const RANGES = {
  latin: "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
};
const fontCss = [["Inter", "inter"], ["JetBrains Mono", "jetbrains-mono"]]
  .flatMap(([family, file]) =>
    Object.entries(RANGES).map(
      ([subset, range]) =>
        `@font-face{font-family:"${family}";font-style:normal;font-display:swap;font-weight:100 900;unicode-range:${range};src:url(data:font/woff2;base64,${b64("vendor", "fonts", `${file}-${subset}-wght-normal.woff2`)}) format("woff2")}`,
    ),
  )
  .join("\n");

const ui = fs
  .readdirSync(path.join(assets, "ui"))
  .filter((n) => n.endsWith(".js"))
  .sort()
  .map((n) => `<script>/* ui/${n} */\n${noClose(read("ui", n))}</script>`)
  .join("\n");

// Orbit has no local Claude CLI behind /api/ask, so the Ask bar is hidden (Ask via Orbit's own assistant is a later ticket).
const orbitStyle = "<style>#ask{display:none!important}</style>";

const html = read("viewer.html")
  .replace("/*__GRAPH_QUERY__*/", () => noClose(read("graph-query.js")))
  .replace("<!--__ELK_SCRIPT__-->", () => `<script>${noClose(read("vendor", "elk.bundled.js"))}</script>`)
  .replace("/*__FONTS__*/", () => fontCss)
  .replace(/__FLOORPLAN_LOGO__/g, () => `data:image/png;base64,${b64("logo.png")}`)
  .replace(/__FLOORPLAN_FAVICON__/g, () => `data:image/png;base64,${b64("favicon.png")}`)
  .replace("<!--__UI_EXTENSIONS__-->", () => ui)
  .replace("</head>", () => `${orbitStyle}</head>`);

for (const marker of ["/*__FLOORPLAN_DATA__*/null", "__FLOORPLAN_TITLE__"])
  if (html.split(marker).length !== 2) throw new Error(`expected exactly one ${marker}`);
if (/\/\*__|<!--__|__FLOORPLAN_(LOGO|FAVICON)__/.test(html.replace("/*__FLOORPLAN_DATA__*/", ""))) throw new Error("unfilled placeholder left in template");

fs.writeFileSync(
  path.join(root, "template.generated.ts"),
  `// GENERATED by scripts/build-floorplan-template.mjs — do not edit. Floorplan © Hayden Smith, MIT (see LICENSE).\nexport const FLOORPLAN_TEMPLATE: string = ${JSON.stringify(html)};\n`,
);
console.log(`template: ${(html.length / 1024).toFixed(0)} KB`);
